import csv,json
rows=list(csv.DictReader(open("tjs_geo.csv",encoding="utf-8")))
markers=json.dumps(rows,ensure_ascii=False)
parts=[]
parts.append("<html><head><meta charset=\"utf-8\"><title>TJS Map</title>")
parts.append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">")
parts.append("<link rel=\"stylesheet\" href=\"https://unpkg.com/leaflet@1.9.4/dist/leaflet.css\">")
parts.append("<script src=\"https://unpkg.com/leaflet@1.9.4/dist/leaflet.js\"></script>")
parts.append("<style>body{margin:0;font-family:sans-serif}.bar{padding:12px;background:#f7f3ea}.btn{display:block;background:#1f6f5b;color:white;text-align:center;text-decoration:none;padding:12px;margin-top:8px;border-radius:8px;font-size:18px}#map{height:78vh;width:100vw}</style></head><body>")
parts.append("<div class=\"bar\"><b>TJS GEO Map</b><br>CelesTrak GEO TLEから抽出したTJSの地図表示<a class=\"btn\" href=\"/cgi-bin/update.py\">最新TLEで更新</a></div>")
parts.append("<div id=\"map\"></div>")
parts.append("<script>")
parts.append("const data = "+markers+";")
parts.append("const map = L.map(\"map\").setView([0,140],2);")
parts.append("L.tileLayer(\"https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png\", {maxZoom: 6, attribution: \"OpenStreetMap\"}).addTo(map);")
parts.append("data.forEach(r => L.marker([parseFloat(r.lat), parseFloat(r.lon)]).addTo(map).bindPopup(r.name + \"<br>NORAD \" + r.norad + \"<br>Lat \" + r.lat + \"<br>Lon \" + r.lon + \"<br>Alt km \" + r.alt_km));")
parts.append("</script></body></html>")
open("tjs_map.html","w",encoding="utf-8").write("\n".join(parts))
print("saved tjs_map.html")
